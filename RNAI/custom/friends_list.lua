=== 詳細操作說明 ===

【添加單個朋友】
  操作: ALT + SHIFT + 右鍵點擊目標
  說明: 對任何玩家或生命體使用攻擊指令即可添加為朋友

【清空朋友列表】
  操作: ALT + SHIFT + 右鍵點擊自己的生命體
  說明: 對自己使用攻擊指令會清空所有朋友

【批量添加朋友（矩形範圍）】
  步驟1: ALT + 右鍵點擊第一個角點 (移動指令)
  步驟2: ALT + 右鍵點擊第二個角點 (移動指令)
  說明: 會選取矩形範圍內所有玩家/生命體為朋友

【全視野範圍添加朋友】
  操作: ALT+SHIFT+右鍵兩次點擊地面
  說明: 第一次設定起始點，第二次完成添加視野內所有玩家為朋友（無上限）

